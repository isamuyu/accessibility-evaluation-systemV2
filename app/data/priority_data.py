import re

_EXACT = {num: (content, stars) for num, content, stars in PRIORITY_ENTRIES}


def lookup_priority(clause_number: str) -> tuple:
    """查条文改造优先级，返回 (改造内容, 星级)。未收录返回 (None, 1)"""
    if not clause_number:
        return None, 1
    if clause_number in _EXACT:
        return _EXACT[clause_number]
    # 去掉字母后缀逐级回退：5.3.6.2b -> 5.3.6.2 -> 聚合表
    base = re.sub(r"[a-z]+$", "", clause_number)
    if base in _EXACT:
        return _EXACT[base]
    if base in _AGGREGATED:
        return _AGGREGATED[base]
    # 再退一级（如 6.2.1.2c -> 6.2.1.2 已在上面处理；6.2.1.2 -> 6.2.1 不需要）
    return None, 1
